package io.coffeeshop.core.domain;

/**
 * Единица измерения ингредиента.
 *
 * <p>Единица — часть контракта между сервисами: количество в граммах бессмысленно
 * без единицы, поэтому она едет вместе с количеством и в рецепте, и в событиях.
 */
public enum Unit {

    /** Вес: кофе, сахар, сироп. */
    GRAM,

    /** Объём: молоко, вода, сливки. */
    MILLILITER,

    /** Штучное: стакан, крышка, палочка. */
    PIECE
}
